def printable(text: str) -> str:
    """Lossless font-safe text: escape unsupported glyphs and control bytes."""
    return "".join(
        char if char in _PATTERNS else f"\\u{ord(char):04x}" for char in text
    )


def append_legend(
    rgb: bytes,
    width: int,
    height: int,
    entries: list[tuple[tuple[int, int, int], str]],
) -> tuple[bytes, int, int]:
    """Add readable two-times-scaled text and 12-pixel colour swatches below."""
    if not entries:
        return rgb, width, height
    labels = [(colour, printable(text)) for colour, text in entries]
    # Reason: wrap rather than producing an unbounded-width PNG for a long name.
    out_width = max(width, min(1200, 36 + max(len(text) for _, text in labels) * 12))
    capacity = max(1, (out_width - 36) // 12)
    lines = [
        (colour, text[i : i + capacity])
        for colour, text in labels
        for i in range(0, len(text), capacity)
    ]
    out_height = height + 12 + len(lines) * 20
    pixels = bytearray(b"\xff\xff\xff" * out_width * out_height)
    for row in range(height):
        offset = row * out_width * 3
        pixels[offset : offset + width * 3] = rgb[
            row * width * 3 : (row + 1) * width * 3
        ]

    def rectangle(x: int, y: int, w: int, h: int, colour: tuple[int, int, int]) -> None:
        for row in range(y, y + h):
            start = (row * out_width + x) * 3
            pixels[start : start + w * 3] = bytes(colour) * w

    for index, (colour, text) in enumerate(lines):
        y = height + 8 + index * 20
        rectangle(8, y, 12, 14, colour)
        for column, char in enumerate(text):
            for row, pattern in enumerate(_PATTERNS[char].split("/")):
                for bit, value in enumerate(pattern):
                    if value == "1":
                        rectangle(
                            28 + column * 12 + bit * 2, y + row * 2, 2, 2, (32, 32, 32)
                        )
    return bytes(pixels), out_width, out_height
